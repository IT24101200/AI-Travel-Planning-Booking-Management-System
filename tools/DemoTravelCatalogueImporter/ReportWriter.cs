using System.Text;

namespace DemoTravelCatalogueImporter;

public static class ReportWriter
{
    private static readonly (string Name, string[] Stops)[] Scenarios =
    [
        ("A - Colombo -> Kandy -> Ella", ["Colombo", "Kandy", "Ella"]),
        ("B - Colombo -> Galle -> Mirissa", ["Colombo", "Galle", "Mirissa"]),
        ("C - Colombo -> Anuradhapura -> Sigiriya", ["Colombo", "Anuradhapura", "Sigiriya"]),
        ("D - Colombo -> Trincomalee -> Batticaloa", ["Colombo", "Trincomalee", "Batticaloa"]),
        ("E - Colombo -> Jaffna -> Anuradhapura", ["Colombo", "Jaffna", "Anuradhapura"]),
        ("Batticaloa -> Colombo -> Ella", ["Batticaloa", "Colombo", "Ella"])
    ];

    public static void WriteAll(
        string repositoryRoot,
        DatabaseTargetInfo target,
        CatalogueDocument document,
        CatalogueSnapshot snapshot,
        ImportPlan plan,
        bool applyRequested,
        ApplyResult? applyResult = null)
    {
        var dryRunPath = Path.Combine(repositoryRoot, "DEMO_TRAVEL_CATALOGUE_IMPORT_DRY_RUN.md");
        var finalPath = Path.Combine(repositoryRoot, "REALISTIC_DEMO_TRAVEL_DATA_IMPORT_REPORT.md");
        File.WriteAllText(dryRunPath, BuildDryRun(target, document, snapshot, plan, applyRequested, applyResult), Encoding.UTF8);
        File.WriteAllText(finalPath, BuildFinalReport(target, document, snapshot, plan, applyRequested, applyResult), Encoding.UTF8);
    }

    private static string BuildDryRun(
        DatabaseTargetInfo target,
        CatalogueDocument document,
        CatalogueSnapshot snapshot,
        ImportPlan plan,
        bool applyRequested,
        ApplyResult? applyResult)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# DEMO TRAVEL CATALOGUE IMPORT DRY RUN");
        sb.AppendLine();
        sb.AppendLine("This report was generated by the isolated importer. Default mode performs read-only database queries and never calls `SaveChanges`.");
        sb.AppendLine();
        AppendEnvironment(sb, target);
        sb.AppendLine("## Current counts");
        AppendCounts(sb, snapshot);
        sb.AppendLine();
        sb.AppendLine("## Planned operations");
        AppendPlanCounts(sb, document, plan);
        sb.AppendLine();
        sb.AppendLine("## Verification and duplicate outcomes");
        AppendIssues(sb, plan);
        sb.AppendLine();
        sb.AppendLine("## Expected counts after a successful approved apply");
        sb.AppendLine($"- Destinations: `{snapshot.Destinations.Count + plan.DestinationsToInsert.Count}`");
        sb.AppendLine($"- Hotels: `{snapshot.Hotels.Count + plan.HotelsToInsert.Count}`");
        sb.AppendLine($"- Rooms: `{snapshot.Rooms.Count + plan.RoomsToInsert.Count}`");
        sb.AppendLine($"- Tours: `{snapshot.Tours.Count + plan.ToursToInsert.Count}`");
        sb.AppendLine($"- TransportOptions: `{snapshot.TransportOptions.Count + plan.TransportToInsert.Count}`");
        sb.AppendLine();
        sb.AppendLine("## Destination coverage");
        AppendDestinationCoverage(sb, snapshot, plan);
        sb.AppendLine();
        sb.AppendLine("## Route coverage");
        AppendRouteCoverage(sb, snapshot, plan);
        sb.AppendLine();
        sb.AppendLine("## AI read-only scenarios");
        AppendScenarios(sb, snapshot, plan);
        sb.AppendLine();
        sb.AppendLine("## Apply gate");
        if (!applyRequested)
        {
            sb.AppendLine("- Mode: `DRY RUN`");
            sb.AppendLine("- Database mutation: `0` (no write flag supplied)");
        }
        else if (!target.WriteApproved)
        {
            sb.AppendLine("- Mode: `--apply requested`");
            sb.AppendLine(target.ProductionConflict
                ? "- Result: `ENVIRONMENT_CONFLICT - production/shared signal detected`"
                : "- Result: `BLOCKED - explicit environment and write approval are required`");
            sb.AppendLine("- Database mutation: `0`");
        }
        else if (applyResult is not null)
        {
            sb.AppendLine("- Mode: `--apply`");
            sb.AppendLine($"- Applied: destinations `{applyResult.DestinationsInserted}`, hotels `{applyResult.HotelsInserted}`, rooms `{applyResult.RoomsInserted}`, tours `{applyResult.ToursInserted}`, transport `{applyResult.TransportInserted}`");
            sb.AppendLine($"- Failed batches: `{applyResult.FailedBatches}`");
        }

        return sb.ToString();
    }

