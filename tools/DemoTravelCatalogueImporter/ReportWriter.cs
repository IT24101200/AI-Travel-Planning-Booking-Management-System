    private static void AppendPlanCounts(StringBuilder sb, CatalogueDocument document, ImportPlan plan)
    {
        sb.AppendLine($"- Destination candidates: `{document.Destinations.Count}`; inserts `{plan.DestinationsToInsert.Count}`");
        sb.AppendLine($"- Hotel candidates: `{document.Hotels.Count}`; inserts `{plan.HotelsToInsert.Count}`");
        sb.AppendLine($"- Room rows: inserts `{plan.RoomsToInsert.Count}`");
        sb.AppendLine($"- Tour candidates: `{document.Tours.Count}`; inserts `{plan.ToursToInsert.Count}`");
        sb.AppendLine($"- Transport rows: inserts `{plan.TransportToInsert.Count}`");
    }

    private static void AppendIssues(StringBuilder sb, ImportPlan plan)
    {
        if (plan.Issues.Count == 0)
        {
            sb.AppendLine("- None");
            return;
        }

        foreach (var group in plan.Issues
                     .GroupBy(i => new { i.Entity, i.Code })
                     .OrderBy(g => g.Key.Entity)
                     .ThenBy(g => g.Key.Code))
        {
            var example = group.First().Detail.Replace("\r", " ").Replace("\n", " ");
            sb.AppendLine($"- `{group.Key.Entity}` / `{group.Key.Code}`: `{group.Count()}`; example: {example}");
        }
    }

    private static void AppendDestinationCoverage(StringBuilder sb, CatalogueSnapshot snapshot, ImportPlan plan)
    {
        var destinationById = snapshot.Destinations.ToDictionary(d => d.Id);
        var hotelById = snapshot.Hotels.ToDictionary(h => h.Id);
        var names = snapshot.Destinations.Select(d => d.Name)
            .Concat(plan.DestinationsToInsert.Select(d => d.Name))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(name => name, StringComparer.OrdinalIgnoreCase);

        sb.AppendLine("| Destination | Active hotels | Active rooms | Active tours | Status |");
        sb.AppendLine("|---|---:|---:|---:|---|");
        foreach (var name in names)
        {
            var destination = snapshot.Destinations.FirstOrDefault(d => Normalizers.Name(d.Name) == Normalizers.Name(name));
            var hotels = destination is null
                ? 0
                : snapshot.Hotels.Count(h => h.DestinationId == destination.Id && h.Status == "Active");
            var hotelIds = destination is null
                ? new HashSet<int>()
                : snapshot.Hotels.Where(h => h.DestinationId == destination.Id && h.Status == "Active").Select(h => h.Id).ToHashSet();
            var rooms = snapshot.Rooms.Count(r => hotelIds.Contains(r.HotelId) && r.Status == "Active");
            var tours = destination is null
                ? plan.ToursToInsert.Count(t => Normalizers.Name(t.Destination) == Normalizers.Name(name))
                : snapshot.Tours.Count(t => t.DestinationId == destination.Id && t.Status == "Active") +
                  plan.ToursToInsert.Count(t => Normalizers.Name(t.Destination) == Normalizers.Name(name));
            var plannedHotels = plan.HotelsToInsert.Count(h => Normalizers.Name(h.Destination) == Normalizers.Name(name));
            var plannedRooms = plan.RoomsToInsert.Count(r => plan.HotelsToInsert.Any(h =>
                Normalizers.Name(h.Name) == Normalizers.Name(r.Hotel) &&
                Normalizers.Name(h.Destination) == Normalizers.Name(name)));
            hotels += plannedHotels;
            rooms += plannedRooms;
            var status = hotels > 0 && rooms > 0 && tours > 0 ? "OK" : "NO_HOTEL_COVERAGE / NO_ROOM_COVERAGE / NO_TOUR_COVERAGE";
            sb.AppendLine($"| {name} | {hotels} | {rooms} | {tours} | {status} |");
        }
    }

    private static void AppendRouteCoverage(StringBuilder sb, CatalogueSnapshot snapshot, ImportPlan plan)
    {
        sb.AppendLine($"Schedule window: `{plan.WindowStart:yyyy-MM-dd}` to `{plan.WindowEnd:yyyy-MM-dd}`; local wall-clock values; capacity `8`; provider `Demo Private Transfer`.");
        sb.AppendLine();
        sb.AppendLine("| From | To | Current active | Planned | Earliest planned | Latest planned | Status |");
        sb.AppendLine("|---|---|---:|---:|---|---|---|");

        var routes = CataloguePlanner.RequiredRoutes()
            .OrderBy(r => r.From, StringComparer.OrdinalIgnoreCase)
            .ThenBy(r => r.To, StringComparer.OrdinalIgnoreCase);

        foreach (var (from, to) in routes)
        {
            var current = snapshot.TransportOptions.Count(t => t.Status == "Active" &&
                Normalizers.Name(t.RouteFrom) == Normalizers.Name(from) &&
                Normalizers.Name(t.RouteTo) == Normalizers.Name(to));
            var planned = plan.TransportToInsert.Where(t =>
                Normalizers.Name(t.RouteFrom) == Normalizers.Name(from) &&
                Normalizers.Name(t.RouteTo) == Normalizers.Name(to)).ToList();
            var status = planned.Count > 0 || current > 0 ? "COVERED" : "NO_ROUTE";
            sb.AppendLine($"| {from} | {to} | {current} | {planned.Count} | {(planned.Count == 0 ? "-" : planned.Min(t => t.DepartureTime).ToString("yyyy-MM-dd"))} | {(planned.Count == 0 ? "-" : planned.Max(t => t.DepartureTime).ToString("yyyy-MM-dd"))} | {status} |");
        }
    }

    private static void AppendScenarios(StringBuilder sb, CatalogueSnapshot snapshot, ImportPlan plan)
    {
        foreach (var scenario in Scenarios)
        {
            var destinationCoverage = scenario.Stops.Select(destination =>
            {
                var destinationRow = snapshot.Destinations.FirstOrDefault(d => Normalizers.Name(d.Name) == Normalizers.Name(destination));
                var activeHotel = destinationRow is not null && snapshot.Hotels.Any(h => h.DestinationId == destinationRow.Id && h.Status == "Active");
                var activeRoom = destinationRow is not null && snapshot.Hotels.Where(h => h.DestinationId == destinationRow.Id && h.Status == "Active")
                    .Select(h => h.Id).Any(id => snapshot.Rooms.Any(r => r.HotelId == id && r.Status == "Active"));
                var plannedHotel = plan.HotelsToInsert.Any(h => Normalizers.Name(h.Destination) == Normalizers.Name(destination));
                var plannedRoom = plan.RoomsToInsert.Any(r => plan.HotelsToInsert.Any(h =>
                    Normalizers.Name(h.Name) == Normalizers.Name(r.Hotel) &&
                    Normalizers.Name(h.Destination) == Normalizers.Name(destination)));
                var tours = (destinationRow is not null && snapshot.Tours.Any(t => t.DestinationId == destinationRow.Id && t.Status == "Active")) ||
                            plan.ToursToInsert.Any(t => Normalizers.Name(t.Destination) == Normalizers.Name(destination));
                return new
                {
                    Hotel = activeHotel || plannedHotel,
                    Room = activeRoom || plannedRoom,
                    Tour = tours
                };
            }).ToList();

            var legs = new List<(string From, string To, int Count, bool Capacity, bool Availability)>();
            for (var index = 0; index < scenario.Stops.Length - 1; index++)
            {
                var from = scenario.Stops[index];
                var to = scenario.Stops[index + 1];
                var current = snapshot.TransportOptions
                    .Where(t => t.Status == "Active" &&
                                Normalizers.Name(t.RouteFrom) == Normalizers.Name(from) &&
                                Normalizers.Name(t.RouteTo) == Normalizers.Name(to) &&
                                t.DepartureTime.Date >= plan.WindowStart.ToDateTime(TimeOnly.MinValue).Date &&
                                t.DepartureTime.Date <= plan.WindowEnd.ToDateTime(TimeOnly.MinValue).Date)
                    .Select(t => (Departure: t.DepartureTime, Capacity: 0))
                    .ToList();
                var planned = plan.TransportToInsert
                    .Where(t => Normalizers.Name(t.RouteFrom) == Normalizers.Name(from) && Normalizers.Name(t.RouteTo) == Normalizers.Name(to))
                    .Select(t => (Departure: t.DepartureTime, Capacity: t.Capacity))
                    .ToList();
                var options = current.Concat(planned).ToList();
                legs.Add((from, to, options.Count, options.Any(o => o.Capacity >= 2 || o.Capacity == 0), options.Count > 0));
            }

            var result = destinationCoverage.All(c => c.Hotel && c.Room && c.Tour) &&
                         legs.All(l => l.Count > 0 && l.Capacity && l.Availability);
            var date = FindCommonDate(plan, scenario.Stops);
            sb.AppendLine($"- **{scenario.Name}**: hotel `{(destinationCoverage.All(c => c.Hotel) ? "PASS" : "FAIL")}`, room `{(destinationCoverage.All(c => c.Room) ? "PASS" : "FAIL")}`, tours `{(destinationCoverage.All(c => c.Tour) ? "PASS" : "FAIL")}`, date `{(date is null ? "none" : date.Value.ToString("yyyy-MM-dd"))}`, result **{(result ? "PASS" : "FAIL")}**.");
            foreach (var leg in legs)
            {
                sb.AppendLine($"  - {leg.From} -> {leg.To}: options `{leg.Count}`, capacity-compatible `{(leg.Capacity ? "yes" : "no")}`, availability-compatible `{(leg.Availability ? "yes" : "no")}`");
            }
        }
    }

    private static DateOnly? FindCommonDate(ImportPlan plan, string[] stops)
    {
        for (var date = plan.WindowStart; date <= plan.WindowEnd; date = date.AddDays(1))
        {
            var allLegs = true;
            for (var index = 0; index < stops.Length - 1; index++)
            {
                var found = plan.TransportToInsert.Any(t =>
                    Normalizers.Name(t.RouteFrom) == Normalizers.Name(stops[index]) &&
                    Normalizers.Name(t.RouteTo) == Normalizers.Name(stops[index + 1]) &&
                    DateOnly.FromDateTime(t.DepartureTime) == date &&
                    t.Capacity >= 2);
                if (!found)
                {
                    allLegs = false;
                    break;
                }
            }

            if (allLegs)
            {
                return date;
            }
        }

        return null;
    }
