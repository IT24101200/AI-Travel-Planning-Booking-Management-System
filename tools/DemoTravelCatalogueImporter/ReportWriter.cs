        sb.AppendLine("# REALISTIC DEMO TRAVEL DATA IMPORT REPORT");
        sb.AppendLine();
        sb.AppendLine("## Result");
        sb.AppendLine();
        if (applyResult is not null)
        {
            sb.AppendLine(applyResult.FailedBatches == 0
                ? "**IMPORTED AND VERIFIED**"
                : "**PARTIALLY IMPORTED**");
        }
        else
        {
            sb.AppendLine(applyRequested
                ? "**BLOCKED**"
                : "**DRY RUN COMPLETE - DATABASE WRITE BLOCKED**");
        }

        sb.AppendLine();
        sb.AppendLine("No schema migration is used. Existing booking-linked catalogue rows are never updated or deleted.");
        sb.AppendLine();
        sb.AppendLine("## Environment");
        AppendEnvironment(sb, target);
        sb.AppendLine($"- Write authorized: `{(target.WriteApproved ? "YES" : "NO")}`");
        sb.AppendLine();
        sb.AppendLine("## Baseline");
        AppendCounts(sb, snapshot);
        sb.AppendLine();
        sb.AppendLine("## Verification");
        sb.AppendLine($"- Hotels researched: `{document.Hotels.Count}`");
        sb.AppendLine($"- Hotels passing import gate: `{plan.HotelsToInsert.Count}`");
        sb.AppendLine($"- Hotels skipped/blocked: `{document.Hotels.Count - plan.HotelsToInsert.Count}`");
        sb.AppendLine($"- Destinations verified for import: `{document.Destinations.Count(d => d.Verified)}` of `{document.Destinations.Count}` candidates");
