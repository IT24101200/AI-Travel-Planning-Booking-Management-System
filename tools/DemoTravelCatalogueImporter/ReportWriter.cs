        sb.AppendLine($"- Hotels: `{snapshot.Hotels.Count}`");
        sb.AppendLine($"- Rooms: `{snapshot.Rooms.Count}`");
        sb.AppendLine($"- Tours: `{snapshot.Tours.Count}`");
        sb.AppendLine($"- TransportOptions: `{snapshot.TransportOptions.Count}`");
        sb.AppendLine($"- Active hotels: `{snapshot.Hotels.Count(h => h.Status == "Active")}`");
        sb.AppendLine($"- Active rooms: `{snapshot.Rooms.Count(r => r.Status == "Active")}`");
        sb.AppendLine($"- Active tours: `{snapshot.Tours.Count(t => t.Status == "Active")}`");
        sb.AppendLine($"- Active transport: `{snapshot.TransportOptions.Count(t => t.Status == "Active")}`");
